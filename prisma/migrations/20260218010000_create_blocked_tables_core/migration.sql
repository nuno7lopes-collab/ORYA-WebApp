      FOREIGN KEY (event_id)
      REFERENCES app_v3.events(id)
      ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'padel_tournament_roles_organization_id_fkey'
