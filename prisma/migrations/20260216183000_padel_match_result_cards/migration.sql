-- Padel live result cards/signatures + captain slot normalization for strong lifecycle semantics.

UPDATE app_v3.padel_pairing_slots
SET
  slot_status = 'FILLED'::app_v3."PadelPairingSlotStatus",
  updated_at = NOW()
WHERE slot_role = 'CAPTAIN'::app_v3."PadelPairingSlotRole"
  AND profile_id IS NOT NULL
  AND slot_status = 'PENDING'::app_v3."PadelPairingSlotStatus";

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'app_v3'
      AND t.typname = 'PadelMatchResultCardStatus'
  ) THEN
    CREATE TYPE app_v3."PadelMatchResultCardStatus" AS ENUM (
      'PENDING_SIGNATURES',
      'CONFIRMED',
      'CONFLICTED',
      'CANCELLED'
    );
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS app_v3.padel_match_result_cards (
  env text NOT NULL DEFAULT 'prod',
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  match_id integer NOT NULL,
  organization_id integer NOT NULL,
  event_id integer NOT NULL,
  submitted_by_user_id uuid,
  payload jsonb NOT NULL,
  payload_hash text NOT NULL,
  status app_v3."PadelMatchResultCardStatus" NOT NULL DEFAULT 'PENDING_SIGNATURES',
  confirmed_at timestamptz(6),
  conflict_at timestamptz(6),
  cancelled_at timestamptz(6),
  applied_at timestamptz(6),
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  updated_at timestamptz(6) NOT NULL DEFAULT now(),
  CONSTRAINT padel_match_result_cards_pkey PRIMARY KEY (id),
  CONSTRAINT padel_match_result_cards_match_fk
    FOREIGN KEY (match_id)
    REFERENCES app_v3.padel_matches(id)
    ON DELETE CASCADE
    ON UPDATE NO ACTION
);

CREATE INDEX IF NOT EXISTS padel_match_result_cards_match_idx ON app_v3.padel_match_result_cards(match_id);
CREATE INDEX IF NOT EXISTS padel_match_result_cards_event_idx ON app_v3.padel_match_result_cards(event_id);
CREATE INDEX IF NOT EXISTS padel_match_result_cards_org_idx ON app_v3.padel_match_result_cards(organization_id);
CREATE INDEX IF NOT EXISTS padel_match_result_cards_status_idx ON app_v3.padel_match_result_cards(status);
CREATE INDEX IF NOT EXISTS padel_match_result_cards_hash_idx ON app_v3.padel_match_result_cards(payload_hash);

CREATE TABLE IF NOT EXISTS app_v3.padel_match_result_signatures (
  env text NOT NULL DEFAULT 'prod',
  id integer GENERATED BY DEFAULT AS IDENTITY,
  result_card_id uuid NOT NULL,
  side app_v3."PadelMatchSide" NOT NULL,
  user_id uuid NOT NULL,
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  CONSTRAINT padel_match_result_signatures_pkey PRIMARY KEY (id),
  CONSTRAINT padel_match_result_signatures_card_fk
    FOREIGN KEY (result_card_id)
    REFERENCES app_v3.padel_match_result_cards(id)
    ON DELETE CASCADE
    ON UPDATE NO ACTION,
  CONSTRAINT padel_match_result_signatures_card_side_uq UNIQUE (result_card_id, side),
  CONSTRAINT padel_match_result_signatures_card_user_uq UNIQUE (result_card_id, user_id)
);

CREATE INDEX IF NOT EXISTS padel_match_result_signatures_card_idx ON app_v3.padel_match_result_signatures(result_card_id);
CREATE INDEX IF NOT EXISTS padel_match_result_signatures_user_idx ON app_v3.padel_match_result_signatures(user_id);
