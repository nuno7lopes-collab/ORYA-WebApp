WITH org_seed AS (
  SELECT DISTINCT s.organization_id
  FROM app_v3.services s
  UNION
  SELECT DISTINCT c.organization_id
  FROM app_v3.padel_clubs c
),
default_categories AS (
  SELECT
    organization_id,
    domain,
    slug,
    label,
    sort_order
  FROM org_seed
  CROSS JOIN (
    VALUES
      ('COURT'::app_v3."ReservationCategoryDomain", 'campo-padel', 'Reserva de Campo', 10),
      ('CLASS'::app_v3."ReservationCategoryDomain", 'aulas', 'Aulas', 20),
      ('SERVICE'::app_v3."ReservationCategoryDomain", 'servicos', 'Serviços', 30)
  ) AS defaults(domain, slug, label, sort_order)
),
service_category_seed AS (
  SELECT DISTINCT
    s.organization_id,
    CASE
      WHEN s.kind = 'COURT' THEN 'COURT'::app_v3."ReservationCategoryDomain"
      WHEN s.kind = 'CLASS' THEN 'CLASS'::app_v3."ReservationCategoryDomain"
      ELSE 'SERVICE'::app_v3."ReservationCategoryDomain"
    END AS domain,
    CASE
      WHEN s.kind = 'COURT' THEN 'campo-padel'
      WHEN s.kind = 'CLASS' THEN 'aulas'
      WHEN lower(COALESCE(NULLIF(btrim(s.category_tag), ''), '')) IN ('aulas', 'aula', 'lesson', 'lessons', 'class', 'classes', 'treino', 'treinos') THEN 'aulas'
      WHEN lower(COALESCE(NULLIF(btrim(s.category_tag), ''), '')) IN ('padel', 'paddle', 'campo', 'campos', 'court', 'courts', 'reserva-campo', 'reserva-de-campo') THEN 'campo-padel'
      WHEN COALESCE(NULLIF(btrim(s.category_tag), ''), '') <> '' THEN
        left(
          regexp_replace(lower(btrim(s.category_tag)), '[^a-z0-9]+', '-', 'g'),
          60
        )
      ELSE 'servicos'
    END AS slug,
    CASE
      WHEN s.kind = 'COURT' THEN 'Reserva de Campo'
      WHEN s.kind = 'CLASS' THEN 'Aulas'
      WHEN lower(COALESCE(NULLIF(btrim(s.category_tag), ''), '')) IN ('aulas', 'aula', 'lesson', 'lessons', 'class', 'classes', 'treino', 'treinos') THEN 'Aulas'
      WHEN lower(COALESCE(NULLIF(btrim(s.category_tag), ''), '')) IN ('padel', 'paddle', 'campo', 'campos', 'court', 'courts', 'reserva-campo', 'reserva-de-campo') THEN 'Reserva de Campo'
      WHEN COALESCE(NULLIF(btrim(s.category_tag), ''), '') <> '' THEN left(btrim(s.category_tag), 80)
      ELSE 'Serviços'
    END AS label,
    40 AS sort_order
  FROM app_v3.services s
)
