BEGIN
  CREATE TYPE app_v3."ReservationCategoryDomain" AS ENUM ('COURT', 'CLASS', 'SERVICE');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END
$$;

CREATE TABLE IF NOT EXISTS app_v3.reservation_categories (
  env             text NOT NULL DEFAULT 'prod',
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  domain          app_v3."ReservationCategoryDomain" NOT NULL,
  slug            text NOT NULL,
  label           text NOT NULL,
  is_active       boolean NOT NULL DEFAULT true,
  sort_order      integer NOT NULL DEFAULT 0,
  created_at      timestamptz(6) NOT NULL DEFAULT now(),
  updated_at      timestamptz(6) NOT NULL DEFAULT now(),
  CONSTRAINT reservation_categories_org_fk
    FOREIGN KEY (organization_id)
    REFERENCES app_v3.organizations(id)
    ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS reservation_categories_org_domain_slug_unique
  ON app_v3.reservation_categories (organization_id, domain, slug);

CREATE INDEX IF NOT EXISTS reservation_categories_org_domain_active_idx
  ON app_v3.reservation_categories (organization_id, domain, is_active);

ALTER TABLE app_v3.services
  ADD COLUMN IF NOT EXISTS category_id integer;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'services_category_id_fkey'
  ) THEN
    ALTER TABLE app_v3.services
      ADD CONSTRAINT services_category_id_fkey
      FOREIGN KEY (category_id)
      REFERENCES app_v3.reservation_categories(id)
      ON DELETE SET NULL;
  END IF;
END
$$;

