CREATE TABLE IF NOT EXISTS app_v3.refund_policy_versions (
  env text NOT NULL DEFAULT 'prod',
  id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  organization_id integer NOT NULL,
  event_id integer,
  policy_version text NOT NULL,
  fee_bps integer NOT NULL DEFAULT 0,
  fee_fixed_cents integer NOT NULL DEFAULT 0,
  fee_payer app_v3."RefundFeePayer" NOT NULL DEFAULT 'CUSTOMER',
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  created_by_user_id uuid,
  CONSTRAINT refund_policy_versions_pkey PRIMARY KEY (id)
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'refund_policy_versions_organization_id_fkey'
      AND connamespace = 'app_v3'::regnamespace
  ) THEN
    ALTER TABLE app_v3.refund_policy_versions
      ADD CONSTRAINT refund_policy_versions_organization_id_fkey
      FOREIGN KEY (organization_id)
      REFERENCES app_v3.organizations(id)
      ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'refund_policy_versions_event_id_fkey'
      AND connamespace = 'app_v3'::regnamespace
  ) THEN
    ALTER TABLE app_v3.refund_policy_versions
      ADD CONSTRAINT refund_policy_versions_event_id_fkey
      FOREIGN KEY (event_id)
      REFERENCES app_v3.events(id)
      ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'refund_policy_versions_org_event_version_uq'
      AND connamespace = 'app_v3'::regnamespace
  ) THEN
    ALTER TABLE app_v3.refund_policy_versions
      ADD CONSTRAINT refund_policy_versions_org_event_version_uq
      UNIQUE (organization_id, event_id, policy_version);
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS refund_policy_versions_org_event_idx
  ON app_v3.refund_policy_versions (organization_id, event_id);

