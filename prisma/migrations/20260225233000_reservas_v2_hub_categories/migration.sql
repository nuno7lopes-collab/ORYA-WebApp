SELECT
  seed.organization_id,
  seed.domain,
  CASE
    WHEN seed.slug IS NULL OR btrim(seed.slug) = '' THEN 'servicos'
    ELSE btrim(seed.slug)
  END AS slug,
  CASE
    WHEN seed.label IS NULL OR btrim(seed.label) = '' THEN 'Serviços'
    ELSE btrim(seed.label)
  END AS label,
  seed.sort_order,
  now(),
  now()
FROM (
  SELECT * FROM default_categories
  UNION
  SELECT * FROM service_category_seed
) AS seed
ON CONFLICT (organization_id, domain, slug) DO NOTHING;

WITH service_slug AS (
  SELECT
    s.id AS service_id,
    s.organization_id,
    CASE
      WHEN s.kind = 'COURT' THEN 'COURT'::app_v3."ReservationCategoryDomain"
      WHEN s.kind = 'CLASS' THEN 'CLASS'::app_v3."ReservationCategoryDomain"
      ELSE 'SERVICE'::app_v3."ReservationCategoryDomain"
    END AS domain,
    CASE
      WHEN s.kind = 'COURT' THEN 'campo-padel'
      WHEN s.kind = 'CLASS' THEN 'aulas'
      WHEN lower(COALESCE(NULLIF(btrim(s.category_tag), ''), '')) IN ('aulas', 'aula', 'lesson', 'lessons', 'class', 'classes', 'treino', 'treinos') THEN 'aulas'
      WHEN lower(COALESCE(NULLIF(btrim(s.category_tag), ''), '')) IN ('padel', 'paddle', 'campo', 'campos', 'court', 'courts', 'reserva-campo', 'reserva-de-campo') THEN 'campo-padel'
      WHEN COALESCE(NULLIF(btrim(s.category_tag), ''), '') <> '' THEN
        left(
          regexp_replace(lower(btrim(s.category_tag)), '[^a-z0-9]+', '-', 'g'),
          60
        )
      ELSE 'servicos'
    END AS slug
  FROM app_v3.services s
),
category_match AS (
  SELECT
    svc.service_id,
    cat.id AS category_id
  FROM service_slug svc
  JOIN app_v3.reservation_categories cat
    ON cat.organization_id = svc.organization_id
   AND cat.domain = svc.domain
   AND cat.slug = CASE
     WHEN svc.slug IS NULL OR btrim(svc.slug) = '' THEN 'servicos'
     ELSE btrim(svc.slug)
   END
)
UPDATE app_v3.services s
SET category_id = match.category_id
FROM category_match match
WHERE s.id = match.service_id
  AND s.category_id IS DISTINCT FROM match.category_id;

WITH fallback_category AS (
  SELECT
    s.id AS service_id,
    cat.id AS category_id
  FROM app_v3.services s
  JOIN app_v3.reservation_categories cat
    ON cat.organization_id = s.organization_id
   AND cat.slug = CASE
     WHEN s.kind = 'COURT' THEN 'campo-padel'
     WHEN s.kind = 'CLASS' THEN 'aulas'
     ELSE 'servicos'
   END
   AND cat.domain = CASE
     WHEN s.kind = 'COURT' THEN 'COURT'::app_v3."ReservationCategoryDomain"
     WHEN s.kind = 'CLASS' THEN 'CLASS'::app_v3."ReservationCategoryDomain"
     ELSE 'SERVICE'::app_v3."ReservationCategoryDomain"
   END
)
UPDATE app_v3.services s
SET category_id = f.category_id
FROM fallback_category f
WHERE s.id = f.service_id
  AND s.category_id IS NULL;

WITH courts AS (
  SELECT
    c.id AS court_id,
    c.name,
    c.description,
    c.is_active,
    club.organization_id
  FROM app_v3.padel_club_courts c
  JOIN app_v3.padel_clubs club
    ON club.id = c.padel_club_id
  WHERE c.deleted_at IS NULL
    AND club.deleted_at IS NULL
),
service_court_candidates AS (
  SELECT
    s.organization_id,
    rr.court_id,
    s.id AS service_id
  FROM app_v3.services s
  JOIN app_v3.service_resources sr
    ON sr.service_id = s.id
  JOIN app_v3.reservation_resources rr
    ON rr.id = sr.resource_id
  WHERE s.kind = 'COURT'
    AND s.is_active = true
    AND rr.court_id IS NOT NULL
    AND rr.is_active = true
),
ranked_candidates AS (
  SELECT
    organization_id,
    court_id,
    service_id,
    row_number() OVER (PARTITION BY organization_id, court_id ORDER BY service_id ASC) AS rn,
    count(*) OVER (PARTITION BY organization_id, court_id) AS candidate_count
  FROM service_court_candidates
),
resolved_service AS (
  SELECT
    organization_id,
    court_id,
    service_id
  FROM ranked_candidates
  WHERE rn = 1
    AND candidate_count = 1
),
fallback_service AS (
  SELECT
    s.organization_id,
    min(s.id) AS service_id
  FROM app_v3.services s
  WHERE s.kind = 'COURT'
    AND s.is_active = true
  GROUP BY s.organization_id
),
chosen_mapping AS (
  SELECT
    courts.organization_id,
    courts.court_id,
    COALESCE(resolved_service.service_id, fallback_service.service_id) AS service_id,
    resolved_service.service_id IS NOT NULL AS has_unique_mapping,
    courts.name,
    courts.description,
    courts.is_active
  FROM courts
  LEFT JOIN resolved_service
    ON resolved_service.organization_id = courts.organization_id
   AND resolved_service.court_id = courts.court_id
  LEFT JOIN fallback_service
    ON fallback_service.organization_id = courts.organization_id
  WHERE COALESCE(resolved_service.service_id, fallback_service.service_id) IS NOT NULL
)
INSERT INTO app_v3.court_booking_configs (
  organization_id,
  court_id,
  backing_service_id,
  category_id,
  display_name,
  display_description,
  cover_image_url,
  is_active,
  created_at,
  updated_at
)
SELECT
  chosen.organization_id,
  chosen.court_id,
  chosen.service_id,
  svc.category_id,
  COALESCE(NULLIF(btrim(chosen.name), ''), 'Campo #' || chosen.court_id::text) AS display_name,
  NULLIF(btrim(chosen.description), '') AS display_description,
  svc.cover_image_url,
  CASE
    WHEN chosen.has_unique_mapping THEN chosen.is_active
    ELSE false
  END AS is_active,
  now(),
  now()
FROM chosen_mapping chosen
JOIN app_v3.services svc
  ON svc.id = chosen.service_id
ON CONFLICT (court_id) DO UPDATE
SET
  organization_id = EXCLUDED.organization_id,
  backing_service_id = EXCLUDED.backing_service_id,
  category_id = EXCLUDED.category_id,
  display_name = EXCLUDED.display_name,
  display_description = EXCLUDED.display_description,
  cover_image_url = EXCLUDED.cover_image_url,
  is_active = EXCLUDED.is_active,
  updated_at = now();
